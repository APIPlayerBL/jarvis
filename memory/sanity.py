_SHORT_UNKNOWN_MAX = 3                                                           
_REPEAT_HARD = 3                                   
_REPEAT_RATIO_MIN_LEN = 4                                                      

_PREFIX_LEN = 5
_PREFIX_KEYS = tuple(w[: _PREFIX_LEN] for w in KNOWN if len(w) >= _PREFIX_LEN)
_PREFIX_SET = frozenset(_PREFIX_KEYS)

_WORD_RE = re.compile(r"[^\w\s]", re.UNICODE)


def _discovery_names() -> frozenset[str]:
    try:
        raw = json.loads(_DISCOVERY_INDEX.read_text(encoding="utf-8"))
    except Exception:
        return frozenset()
    return frozenset(str(k).lower().replace("ё", "е") for k in raw)


_DISC_NAMES = _discovery_names()


def _tokens(text: str) -> list[str]:
    text = (text or "").lower().replace("ё", "е")
    text = _WORD_RE.sub(" ", text)
    return [t for t in text.split() if t]


@lru_cache(maxsize=4096)
def _is_known(token: str) -> bool:
    if token in KNOWN or token in _DISC_NAMES:
        return True
    if len(token) < _PREFIX_LEN:
        return False
    return token[:_PREFIX_LEN] in _PREFIX_SET


def passes(text: str) -> bool:
    """True = пропустить в brain (команда или болтовня). False = переспросить."""
    tokens = _tokens(text)
    if not tokens:
        return False

    meaningful = [t for t in tokens if t not in STOP]
    if not meaningful:
        return False

    counts = Counter(meaningful)
    if counts.most_common(1)[0][1] >= _REPEAT_HARD:
        return False
    if len(meaningful) >= _REPEAT_RATIO_MIN_LEN and len(counts) * 2 <= len(meaningful):
        return False

    known = sum(1 for t in meaningful if _is_known(t))
    if known == 0:
        return False
    return True


def refresh_discovery_names() -> None:
    """Подхватить пересобранный индекс без перезапуска процесса."""
    global _DISC_NAMES
    _DISC_NAMES = _discovery_names()
    _is_known.cache_clear()


